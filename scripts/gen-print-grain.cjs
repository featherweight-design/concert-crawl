#!/usr/bin/env node
/**
 * Regenerate the baked grain tile used by <IdentityArtPrint /> (#72).
 *
 * Satori has no SVG <filter> support, so the on-screen feTurbulence grain
 * cannot be server-rendered. This bakes the equivalent noise into a small
 * deterministic PNG that satori CAN tile via backgroundImage.
 *
 * Usage: node scripts/gen-print-grain.cjs
 */
const zlib = require('node:zlib')
const fs = require('node:fs')
const path = require('node:path')

const SIZE = 32
const OUT = path.join(
  __dirname,
  '..',
  'apps/web/src/components/consumer/identity-art/print-grain.ts',
)

// Same LCG the identity-art RNG uses, seeded with the FNV-1a offset basis, so
// the texture is byte-identical on every regeneration.
let state = 0x811c9dc5 >>> 0
const rnd = () => {
  state = (Math.imul(state, 1664525) + 1013904223) >>> 0
  return state / 0xffffffff
}

const raw = []
for (let y = 0; y < SIZE; y++) {
  raw.push(0) // PNG per-scanline filter byte
  for (let x = 0; x < SIZE; x++) {
    const noise = rnd()
    // Grayscale + alpha: half the speckle darkens, half lightens, and the
    // alpha ramps with distance from mid so the tile reads as film grain.
    raw.push(noise < 0.5 ? 0 : 255, Math.round(Math.abs(noise - 0.5) * 2 * 255))
  }
}

const crcTable = []
for (let n = 0; n < 256; n++) {
  let cc = n
  for (let k = 0; k < 8; k++) cc = cc & 1 ? 0xedb88320 ^ (cc >>> 1) : cc >>> 1
  crcTable[n] = cc >>> 0
}
const crc = (buf) => {
  let cc = 0xffffffff
  for (const byte of buf) cc = crcTable[(cc ^ byte) & 0xff] ^ (cc >>> 8)
  return (cc ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const typed = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const sum = Buffer.alloc(4)
  sum.writeUInt32BE(crc(typed))
  return Buffer.concat([len, typed, sum])
}

const ihdr = Buffer.alloc(13)
ihdr.writeUInt32BE(SIZE, 0)
ihdr.writeUInt32BE(SIZE, 4)
ihdr[8] = 8 // bit depth
ihdr[9] = 4 // colour type: grayscale + alpha
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('IDAT', zlib.deflateSync(Buffer.from(raw), { level: 9 })),
  chunk('IEND', Buffer.alloc(0)),
])

const source = `// GENERATED by scripts/gen-print-grain.cjs — do not hand-edit.
//
// Baked grain tile for satori (\`next/og\`) rendering. The on-screen
// <IdentityArt /> makes grain from an SVG <filter> + feTurbulence data-URI.
// Satori implements no SVG filter primitives, so feTurbulence renders as
// nothing at all — silently, which is the failure mode the render-through test
// exists to catch. This is the same noise pre-rasterised: a 32x32
// grayscale+alpha PNG of deterministic speckle, tiled via \`backgroundImage\` +
// \`backgroundRepeat: 'repeat'\`. \`mixBlendMode\` is also unsupported, so the
// visual weight is carried by opacity alone.
export const PRINT_GRAIN_TILE_PX = ${SIZE}

export const PRINT_GRAIN_PNG =
  'data:image/png;base64,${png.toString('base64')}'
`

fs.writeFileSync(OUT, source)
process.stdout.write(`wrote ${OUT} (${png.length} bytes PNG)\n`)
