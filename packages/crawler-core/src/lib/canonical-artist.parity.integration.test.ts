import { describe, it, expect } from 'vitest'
import { sql } from 'drizzle-orm'
import { db } from '@concert-crawl/db'
import { latinExtendedSql } from '@concert-crawl/types'
import { canonicalizeArtist } from './canonical-artist.js'

/**
 * Parity test for canonical_artist's Latin Extended handling (#648).
 *
 * The static guard in packages/types/src/latin-extended-sql.test.ts proves the
 * migration files carry the same map as the JS side. This test proves the map
 * actually BEHAVES the same once Postgres executes it — specifically that the
 * 1→N expansions (Æ→ae, Œ→oe, ß→ss, Þ→th) survive. `translate()` is strictly
 * 1→1 and would silently delete them; only a real database can demonstrate
 * that the replace() chain avoids that.
 *
 * Inputs are deliberately separator-free so the whole JS pipeline is
 * reproducible in SQL: NFD + combining-mark strip → Latin Extended map →
 * lowercase → whitespace collapse → trim. The separator split in
 * canonicalizeArtist has no interaction with this map (every mapped char is a
 * letter that maps to letters, so no separator can be created or destroyed).
 */

/**
 * Single-quote a literal for sql.raw(). The inputs are test constants, not
 * user data, but doubling embedded quotes keeps the helper honest if someone
 * adds an apostrophe-bearing case later.
 */
const sqlLiteral = (value: string): string => `'${value.replaceAll("'", "''")}'`

const PARITY_INPUTS: { label: string; input: string }[] = [
  { label: 'plain ASCII baseline', input: 'Earl Sweatshirt' },
  { label: 'NFD-decomposable diacritics', input: 'Sigur Rós' },
  { label: 'pre-decomposed combining acute', input: 'Beyoncé' },

  // The original 2026-06-17 incident chars.
  { label: 'Ø uppercase', input: 'LØLØ' },
  { label: 'ø lowercase', input: 'Eivør' },

  // #648 1→1 additions.
  { label: 'Ł uppercase', input: 'ŁODZ Beat' },
  { label: 'ł lowercase', input: 'Białystok Sound' },
  { label: 'Ð uppercase', input: 'Ðjango Reinhardt' },
  { label: 'ð lowercase', input: 'Eivør Pálsdóttir ðe Band' },
  { label: 'Đ uppercase', input: 'Đorđe Balašević' },
  { label: 'đ lowercase', input: 'nađa' },

  // #648 1→N additions — the translate() truncation trap.
  { label: 'Æ uppercase', input: 'ÆRØSKØBING' },
  { label: 'æ lowercase', input: 'Ærøskøbing Brass' },
  { label: 'Œ uppercase', input: 'CŒUR DE PIRATE' },
  { label: 'œ lowercase', input: 'Cœur de Pirate' },
  { label: 'ẞ uppercase', input: 'GROẞSTADTGEFLÜSTER' },
  { label: 'ß lowercase', input: 'Großstadtgeflüster' },
  { label: 'Þ uppercase', input: 'ÞEYR' },
  { label: 'þ lowercase', input: 'Þeyr' },

  // Several mapped chars in one string — proves the replace() chain composes
  // and that no substitution eats another's output.
  { label: 'all new chars at once', input: 'Łæœßþðđø ÆŒẞÞÐĐØ' },

  // Whitespace handling around the mapped chars.
  { label: 'collapsed whitespace', input: '  Þeyr   og   Æther  ' },
]

describe('canonical_artist — Latin Extended SQL / JS parity', () => {
  it.each(PARITY_INPUTS)('matches on: $label', async ({ input }) => {
    // Reference SQL. The Latin Extended fragment is generated by the shared
    // latinExtendedSql() helper — the exact string the migrations embed — so
    // this test can never validate a different expression from the one that
    // ships.
    const latin = latinExtendedSql(
      `regexp_replace(normalize(${sqlLiteral(input)}, NFD), '[̀-ͯ]', '', 'g')`,
    )

    const rows = await db.execute<{ canonical: string }>(
      sql.raw(`
        SELECT trim(
          regexp_replace(lower(${latin}), '\\s+', ' ', 'g')
        ) AS canonical
      `),
    )

    expect(rows[0]?.canonical).toBe(canonicalizeArtist(input))
  })
})
